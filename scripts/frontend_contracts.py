"""Generate TypeScript schema aliases from the checked-in application OpenAPI."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def expression(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    for operator in ("anyOf", "oneOf", "allOf"):
        if operator in schema:
            return "(" + (" & " if operator == "allOf" else " | ").join(expression(x) for x in schema[operator]) + ")"
    kind = schema.get("type")
    if kind in ("number", "integer"): return "number"
    if kind in ("string", "boolean", "null"): return kind
    if kind == "array":
        if "prefixItems" in schema: return "[" + ", ".join(expression(s) for s in schema["prefixItems"]) + "]"
        return "Array<" + expression(schema.get("items", {})) + ">"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            return "{\n" + "\n".join("  " + json.dumps(k) + ("" if k in required else "?") + ": " + expression(v) + ";" for k, v in schema["properties"].items()) + "\n}"
        additional = schema.get("additionalProperties", {})
        return "Record<string, " + (expression(additional) if isinstance(additional, dict) else "unknown") + ">"
    return "unknown"


def main():
    schema = json.loads((ROOT / "docs/openapi.json").read_text(encoding="utf-8"))
    output = "// Generated by scripts/frontend_contracts.py from docs/openapi.json.\n"
    for name, value in sorted(schema["components"]["schemas"].items()):
        output += f"export type {name} = {expression(value)};\n\n"
    target = ROOT / "frontend/src/lib/contracts.ts"
    if "--check" in sys.argv:
        assert target.read_text(encoding="utf-8") == output, "Regenerate frontend contracts"
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output, encoding="utf-8", newline="\n")
    print(f"Verified {len(schema['components']['schemas'])} generated TypeScript contracts")


if __name__ == "__main__": main()
